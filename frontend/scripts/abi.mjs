// Writes the contract ABIs the page uses, from the Foundry build output in ../out.
// Run `forge build` in the repository root first, then `npm run abi` here.
import { readFileSync, writeFileSync } from "node:fs";

const contracts = [
  ["ProvingGroundHook", "hookAbi", "hook"],
  ["ProvingGroundVault", "vaultAbi", "vault"],
];

for (const [name, exportName, file] of contracts) {
  const artifact = JSON.parse(readFileSync(new URL(`../../out/${name}.sol/${name}.json`, import.meta.url), "utf8"));
  const abi = artifact.abi.filter((item) => item.type !== "constructor");
  writeFileSync(
    new URL(`../src/abi/${file}.ts`, import.meta.url),
    `// Generated by scripts/abi.mjs from out/${name}.sol/${name}.json. Do not edit.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  console.log(`${file}.ts: ${abi.length} entries`);
}
